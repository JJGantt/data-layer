// A saved recipe: a meal you make often, stored once so it can be logged by name.
//
// Its ingredients are the SAME structured rows a logged meal carries — food/amount/unit, per-
// ingredient macros, produce classification — because logging a recipe expands into exactly those
// (nutrition.ts, resolveItemIngredients). That is the whole point of the shape: "log my overnight
// oats" has to produce the identical entry to typing the six components out, produce totals and all.
//
// The parent row's calories/protein/carbs/fat are a CACHED ROLLUP, never an input. Same rule as
// nutrition_entries: the ingredients are the truth and every write re-derives the totals from them.
import { getClient } from './client.js';
import { now, uuid, ValidationError } from './helpers.js';
import {
  ingLabel, normalizeIngredients, produceRollup, rollup,
  type MacroTotals, type NutritionIngredient, type ProduceRollup,
} from './ingredients.js';

// A recipe ingredient is a nutrition ingredient plus an optional prep note ("drained", "the tub that
// says 24 g a scoop"). The note is recipe-only — it never travels into a logged entry.
export interface RecipeIngredient extends NutritionIngredient { notes?: string | null }

export interface Recipe {
  id: string; name: string; notes: string; tags: string[];
  ingredients: RecipeIngredient[]; steps: string[];
  nutrition: MacroTotals; produce: ProduceRollup;
  created: string; updated: string;
}

// Rows as they come back from recipe_ingredients → the shape normalizeIngredients() expects.
function rowToRaw(row: any): any {
  return {
    food: row.food, amount: row.amount, unit: row.unit || '',
    calories: row.calories, protein_g: row.protein_g, carbs_g: row.carbs_g, fat_g: row.fat_g,
    ...(row.produce_type ? { produce_g: row.produce_g, produce_type: row.produce_type } : {}),
  };
}

// Assemble whole recipes from the four tables in four queries, not four per recipe. Names are
// REGENERATED by normalizeIngredients() from food/amount/unit rather than stored, so a label can
// never disagree with the amount beside it.
async function assemble(rows: any[]): Promise<Recipe[]> {
  if (!rows.length) return [];
  const sb = getClient();
  const ids = rows.map(r => r.id);
  const [{ data: tagRows }, { data: ingRows }, { data: stepRows }] = await Promise.all([
    sb.from('recipe_tags').select('recipe_id, tag').in('recipe_id', ids).order('tag'),
    sb.from('recipe_ingredients').select('*').in('recipe_id', ids).order('sort_order'),
    sb.from('recipe_steps').select('recipe_id, instruction').in('recipe_id', ids).order('step_num'),
  ]);

  return rows.map((row) => {
    const mine = (ingRows ?? []).filter((g: any) => g.recipe_id === row.id);
    const { ingredients } = normalizeIngredients(mine.map(rowToRaw), `Recipe '${row.name}'`, true);
    const withNotes: RecipeIngredient[] = ingredients.map((g, i) => (
      mine[i].notes ? { ...g, notes: mine[i].notes } : g));
    return {
      id: row.id, name: row.name, notes: row.notes || '',
      tags: (tagRows ?? []).filter((t: any) => t.recipe_id === row.id).map((t: any) => t.tag),
      ingredients: withNotes,
      steps: (stepRows ?? []).filter((s: any) => s.recipe_id === row.id).map((s: any) => s.instruction),
      nutrition: rollup(ingredients),
      produce: produceRollup(ingredients),
      created: row.created, updated: row.updated,
    };
  });
}

export async function listRecipes(tag?: string): Promise<Recipe[]> {
  const sb = getClient();
  if (tag) {
    const { data } = await sb.from('recipe_tags').select('recipe_id').ilike('tag', tag.trim());
    const ids = (data ?? []).map((r: any) => r.recipe_id);
    if (!ids.length) return [];
    const { data: rows } = await sb.from('recipes').select('*').in('id', ids).order('name');
    return assemble(rows ?? []);
  }
  const { data: rows } = await sb.from('recipes').select('*').order('name');
  return assemble(rows ?? []);
}

// Look a recipe up the way it gets referred to out loud. Exact (case-insensitive) first, then a
// contains match — "my oats" and "gochujang tofu" have to reach the recipe without the caller
// knowing it is filed as "Overnight Oats". An ambiguous partial raises rather than picking one, so a
// meal is never logged against the wrong recipe.
export async function getRecipe(name: string): Promise<Recipe | null> {
  const sb = getClient();
  const wanted = name.trim();
  if (!wanted) return null;
  const { data: exact } = await sb.from('recipes').select('*').ilike('name', wanted);
  let rows = exact ?? [];
  if (!rows.length) {
    const { data: fuzzy } = await sb.from('recipes').select('*').ilike('name', `%${wanted}%`).order('name');
    rows = fuzzy ?? [];
    if (rows.length > 1) {
      throw new ValidationError(`'${wanted}' matches ${rows.length} recipes: ${rows.map((r: any) => r.name).join(', ')}. Use the full name.`);
    }
  }
  if (!rows.length) return null;
  return (await assemble([rows[0]]))[0];
}

export async function saveRecipe(args: {
  name: string; ingredients: any[]; steps?: string[]; notes?: string; tags?: string[];
}): Promise<{ recipe: Recipe; action: string; warnings: string[] }> {
  const sb = getClient();
  const recipeName = (args.name || '').trim();
  if (!recipeName) throw new ValidationError('A recipe needs a name.');

  // Same validator, same floor as a logged meal: every ingredient carries a portion and its macros.
  const { ingredients, warnings } = normalizeIngredients(args.ingredients, `Recipe '${recipeName}'`, true);
  const totals = rollup(ingredients);

  const { data: existing } = await sb.from('recipes').select('id, created').ilike('name', recipeName).maybeSingle();
  const n = now();
  const id = existing?.id || uuid();
  const parent = { name: recipeName, notes: args.notes || '', ...totals, updated: n };

  if (existing) await sb.from('recipes').update(parent).eq('id', id);
  else await sb.from('recipes').insert({ id, ...parent, created: n });

  // Children are replaced wholesale — a save states the recipe as it now is, so a removed ingredient
  // has to actually disappear rather than linger from the previous version.
  await Promise.all([
    sb.from('recipe_tags').delete().eq('recipe_id', id),
    sb.from('recipe_ingredients').delete().eq('recipe_id', id),
    sb.from('recipe_steps').delete().eq('recipe_id', id),
  ]);
  const tags = [...new Set((args.tags || []).map(t => t.trim()).filter(Boolean))];
  const rawNotes = (args.ingredients as any[]).map(g => (g?.notes || '').trim() || null);
  await Promise.all([
    tags.length ? sb.from('recipe_tags').insert(tags.map(tag => ({ recipe_id: id, tag }))) : null,
    sb.from('recipe_ingredients').insert(ingredients.map((g, i) => ({
      recipe_id: id, food: g.food, amount: g.amount, unit: g.unit || null, notes: rawNotes[i],
      calories: g.calories, protein_g: g.protein_g, carbs_g: g.carbs_g, fat_g: g.fat_g,
      produce_g: g.produce_g ?? null, produce_type: g.produce_type ?? null, sort_order: i,
    }))),
    (args.steps || []).length
      ? sb.from('recipe_steps').insert((args.steps || []).map((instruction, i) => ({ recipe_id: id, step_num: i + 1, instruction })))
      : null,
  ]);

  return { recipe: (await getRecipe(recipeName))!, action: existing ? 'Updated' : 'Saved', warnings };
}

export async function deleteRecipe(name: string): Promise<Recipe | null> {
  const recipe = await getRecipe(name);
  if (!recipe) return null;
  await getClient().from('recipes').delete().eq('id', recipe.id);   // children cascade
  return recipe;
}

function macroLine(n: MacroTotals): string {
  return `${Math.round(n.calories)} cal · ${n.protein_g}g protein · ${n.carbs_g}g carbs · ${n.fat_g}g fat`;
}

export function formatRecipe(r: Recipe): string {
  const lines = [`## ${r.name}`];
  if (r.tags.length) lines.push(`*${r.tags.join(', ')}*`);
  lines.push('', `**Per serving:** ${macroLine(r.nutrition)}`);
  if (r.produce.veg_g || r.produce.fruit_g) {
    lines.push(`**Produce:** vegetables ${Math.round(r.produce.veg_g)}g (of which dark green ${Math.round(r.produce.dark_green_g)}g) · fruit ${Math.round(r.produce.fruit_g)}g`);
  }
  lines.push('', '| Ingredient | Cal | Protein | Carbs | Fat |', '|---|---|---|---|---|');
  for (const g of r.ingredients) {
    const note = g.notes ? ` *(${g.notes})*` : '';
    lines.push(`| ${ingLabel(g)}${note} | ${g.calories} | ${g.protein_g}g | ${g.carbs_g}g | ${g.fat_g}g |`);
  }
  if (r.steps.length) {
    lines.push('', '**Instructions:**');
    r.steps.forEach((s, i) => lines.push(`${i + 1}. ${s}`));
  }
  if (r.notes) lines.push('', `**Notes:** ${r.notes}`);
  return lines.join('\n');
}

export function formatRecipeList(recipes: Recipe[]): string {
  const lines = [`**${recipes.length} saved recipe${recipes.length === 1 ? '' : 's'}**`, '',
    '| Recipe | Cal | Protein | Carbs | Fat | Tags |', '|---|---|---|---|---|---|'];
  for (const r of recipes) {
    lines.push(`| ${r.name} | ${Math.round(r.nutrition.calories)} | ${r.nutrition.protein_g}g | ${r.nutrition.carbs_g}g | ${r.nutrition.fat_g}g | ${r.tags.join(', ')} |`);
  }
  return lines.join('\n');
}
