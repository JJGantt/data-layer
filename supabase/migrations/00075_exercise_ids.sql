-- An exercise gets an identity of its own, and a set points at it.
--
-- Until now the exercise NAME was the identity: `exercise_catalog.name` was the primary key, and
-- `sets.exercise` / `exercise_muscles.name` were text copies of it. That made a string comparison the
-- thing that decided whether an exercise existed, which is how "overhead tricep extensions" — a
-- plural — came back as an unknown movement for something logged for months (2026-09-01). The
-- alternatives on offer were both bad: fail the log, or register a SECOND catalog row for a movement
-- that already existed and split its history.
--
-- The fix is not better matching. It is to stop asking the question: a caller names an exercise by
-- id, and an id either exists or it does not.
--
-- This migration is deliberately NON-BREAKING. Three writers insert into `sets` today and every one
-- of them passes a name — the data MCP's logSets(), the hub's /api/log-set, and the trigger in
-- 00046 that turns a watch report into a set. Rather than change all three in the same breath as the
-- schema, a trigger reconciles the two columns in BOTH directions, so:
--
--   * a writer passing exercise_id gets the canonical name filled in from the catalog,
--   * a writer passing only a name still works, and gets a correct exercise_id,
--   * a name that is not in the catalog RAISES instead of writing an orphan row.
--
-- So exercise_id is authoritative from the moment this lands, `sets.exercise` becomes a derived copy
-- that can no longer disagree with the catalog, and the callers move over one at a time. The name
-- column is dropped in a later migration, once nothing reads it.

-- 1. The surrogate key. Existing rows are numbered by the identity sequence as the column is added.
alter table exercise_catalog add column id int generated by default as identity;
alter table exercise_catalog add constraint exercise_catalog_id_key unique (id);

-- 2. Sets point at the catalog. Backfilled by name — verified beforehand to cover every row:
--    2054 sets, 31 catalog names, zero that did not resolve.
alter table sets add column exercise_id int references exercise_catalog(id) on update cascade;
update sets s set exercise_id = c.id from exercise_catalog c where lower(s.exercise) = lower(c.name);
alter table sets alter column exercise_id set not null;
create index if not exists sets_exercise_id_idx on sets (exercise_id);

-- 3. The muscle map hangs off the id too. This is the join that every volume figure is derived from,
--    so a name that drifts here silently stops an exercise counting.
alter table exercise_muscles add column exercise_id int
    references exercise_catalog(id) on delete cascade on update cascade;
update exercise_muscles m set exercise_id = c.id from exercise_catalog c where lower(m.name) = lower(c.name);
alter table exercise_muscles alter column exercise_id set not null;

-- 4. Reconcile the two columns on every write, in whichever direction the writer supplied.
--    SECURITY DEFINER + a pinned search_path for the same reason 00046's trigger has them.
create or replace function sets_resolve_exercise() returns trigger
language plpgsql security definer set search_path = public as $$
declare
    c exercise_catalog%rowtype;
begin
    if new.exercise_id is not null then
        -- The id wins. The name is a copy of the catalog's, never the caller's spelling.
        select * into c from exercise_catalog where id = new.exercise_id;
        if not found then
            raise exception 'no exercise with id %', new.exercise_id;
        end if;
        new.exercise := c.name;
    else
        -- Legacy name path. Exact, case-insensitive: no plural or fuzzy matching lives in the
        -- database, because a write that lands on the WRONG exercise is worse than one that fails.
        select * into c from exercise_catalog where lower(name) = lower(trim(new.exercise));
        if not found then
            raise exception 'unknown exercise %; add it to exercise_catalog first', new.exercise;
        end if;
        new.exercise_id := c.id;
        new.exercise := c.name;
    end if;
    return new;
end $$;

drop trigger if exists sets_resolve_exercise_trg on sets;
create trigger sets_resolve_exercise_trg
    before insert or update of exercise, exercise_id on sets
    for each row execute function sets_resolve_exercise();
