-- Task scoring: dated list items earn and drain a third band on the hub's health bar.
--
-- Three things land here, and they only make sense together:
--
--   1. `priority` — how much an item counts, in both directions.
--   2. `task_events` — the completion ledger, written by trigger.
--   3. recurrence stops being a column and becomes materialised rows (`series_id`).
--
-- WHY RECURRENCE HAD TO CHANGE. A repeating row's `due` marches into the future the instant it
-- fires, so "which occurrence was just completed?" has no answer from the row alone, and its
-- `scheduled_at` sits permanently in the past, so a drain computed from it would bleed forever from
-- an item that is behaving correctly. Materialising every occurrence as its own dated row removes
-- both problems by removing the category: there are only one-shots now. Checking off today's does
-- not touch tomorrow's, and a skipped week is seven separate misses rather than one, which is what
-- it actually was.
--
-- The cost is bulk — a month of "brush teeth" is thirty rows — and `series_id` is what pays it: the
-- rows are KNOWN to belong to one request, so a series can be collapsed on a narrow surface and
-- killed in one operation. Inferring the relationship by matching titles would be guesswork over
-- something we can simply record.

-- ---------------------------------------------------------------------------
-- 1. priority + series
-- ---------------------------------------------------------------------------

-- 0 normal, 1 important. The score multiplier is (1 + priority), so a further level is a new value
-- rather than a new mechanism. Score-only: it does not change how the item notifies.
alter table list_items add column if not exists priority smallint not null default 0;

-- Null for a one-off. Otherwise every occurrence generated by one scheduling request shares this.
alter table list_items add column if not exists series_id text;
create index if not exists list_items_series_idx on list_items(series_id) where series_id is not null;

-- ---------------------------------------------------------------------------
-- 2. the completion ledger
-- ---------------------------------------------------------------------------

-- Completions need to outlive their items. The hub hard-purges cleared rows after 30 days
-- (`purgeCleared` in server.js), so a score read off `list_items` would silently restate itself
-- whenever the purge ran. `list_name`, `title` and `priority` are copied rather than joined for the
-- same reason — the row they came from is expected to disappear.
--
-- Only completions are recorded. The DRAIN from an overdue item is never stored: it is derived live
-- from whatever is currently open and dated, so it corrects itself the moment the item is dealt
-- with, and there is no state to fall out of sync.
create table if not exists task_events (
  id           text primary key,
  item_id      text not null,
  occurrence   text not null,   -- the moment it was scheduled for: list_items.scheduled_at
  completed_at text not null,   -- local-naive, same convention as `due`
  priority     smallint not null default 0,
  list_name    text,
  title        text,
  unique (item_id, occurrence)
);
create index if not exists task_events_completed_idx on task_events(completed_at);

alter table task_events enable row level security;   -- no policies: only the service key touches it

-- Written by trigger rather than by callers. Four surfaces remove items — the todo pane's ✕, the
-- iOS widget's ✕, the MCP tools, the hub's own API — across two repos, and every one of them does
-- the same `deleted = true` patch. One trigger cannot be forgotten by a fifth.
--
-- It records every removal of a dated item, including one removed before its moment arrived. The
-- ledger stays complete and the SCORING rule (an item removed before it goes live is worth nothing)
-- lives in one place in the hub, where it can be tuned without a migration.
create or replace function list_items_task_event() returns trigger as $$
begin
  if new.deleted and not old.deleted and new.due is not null then
    insert into task_events (id, item_id, occurrence, completed_at, priority, list_name, title)
    values (gen_random_uuid()::text, new.id,
            coalesce(new.scheduled_at, new.due),
            to_char(now() at time zone 'America/New_York', 'YYYY-MM-DD"T"HH24:MI:SS'),
            coalesce(new.priority, 0), new.list_name,
            coalesce(nullif(btrim(coalesce(new.title, '')), ''), new.text))
    on conflict (item_id, occurrence) do nothing;
  -- Clearing is soft and therefore reversible; the score has to reverse with it.
  elsif old.deleted and not new.deleted then
    delete from task_events
     where item_id = new.id and occurrence = coalesce(new.scheduled_at, new.due);
  end if;
  return new;
end;
$$ language plpgsql;

drop trigger if exists list_items_task_event_trg on list_items;
create trigger list_items_task_event_trg
  after update on list_items
  for each row execute function list_items_task_event();

-- ---------------------------------------------------------------------------
-- 3. materialise the existing repeaters, then remove the mechanism
-- ---------------------------------------------------------------------------

-- The live repeaters are nags rather than genuine recurrences — a way to keep something in view
-- until it was done. That job now belongs to the drain, which escalates for as long as an item sits
-- overdue. They are materialised anyway rather than silently converted to one-shots, because
-- dropping occurrences someone scheduled is not this migration's call to make.

-- The originating row joins its own series.
update list_items set series_id = id
 where repeat_every is not null and deleted = false and series_id is null;

insert into list_items (id, list_name, text, title, due, scheduled_at, series_id, priority,
                        repeat_every, deleted, created, updated)
select gen_random_uuid()::text, i.list_name, i.text, i.title,
       -- A date-only due is an all-day item: keep it that way rather than pinning it to midnight.
       case when i.due like '%T%' then to_char(occ, 'YYYY-MM-DD"T"HH24:MI')
            else to_char(occ, 'YYYY-MM-DD') end,
       case when i.due like '%T%' then to_char(occ, 'YYYY-MM-DD"T"HH24:MI')
            else to_char(occ, 'YYYY-MM-DD') end,
       i.id, coalesce(i.priority, 0), null, false,
       to_char(now() at time zone 'America/New_York', 'YYYY-MM-DD"T"HH24:MI:SS'),
       to_char(now() at time zone 'America/New_York', 'YYYY-MM-DD"T"HH24:MI:SS')
  from list_items i
  cross join lateral generate_series(
         (i.due)::timestamp + (i.repeat_every)::interval,
         (i.due)::timestamp + interval '30 days',
         (i.repeat_every)::interval) as occ
 where i.deleted = false and i.due is not null and i.repeat_every is not null;

-- Stop the originals repeating. The column survives this migration — the DEPLOYED hub still selects
-- it, and PostgREST errors on a missing column, so dropping it here would break every list surface
-- until the redeploy caught up. EXPAND half of an expand/contract pair; 00086 drops it once the hub
-- no longer reads it. Nulling it now is what matters: it stops the running scheduler advancing rows
-- whose occurrences have just been materialised, which would otherwise fire each one twice.
update list_items set repeat_every = null where repeat_every is not null;
